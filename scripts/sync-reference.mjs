#!/usr/bin/env node
// Copies the app's user-facing reference docs into src/content/docs/reference/, exactly
// as they were at one release tag of jamhooks/jamhooks.
//
// The app repo stays the source of truth for these pages: its tests read them and they
// change in the same commit as the behaviour they describe. This script only converts
// them into Starlight pages: the first "# " heading becomes the `title`, links between
// synced files become site links, and links to anything not published here are reduced
// to their text (or point at GitHub, once LINK_TO_SOURCE is on).
//
//   node scripts/sync-reference.mjs                     # the version in jamhooks.version
//   node scripts/sync-reference.mjs --version v1.6.0    # a given tag (and record it)
//   node scripts/sync-reference.mjs --latest            # the newest vX.Y.Z tag
//   ... --repo ../jamhooks                              # the app clone to read (default)
//
// Files are read with `git show <tag>:<path>`, so the clone may have anything checked
// out; it only needs the tag.

import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const VERSION_FILE = resolve(ROOT, 'jamhooks.version');
const OUT_DIR = resolve(ROOT, 'src/content/docs/reference');
const APP_REPO_URL = 'https://github.com/jamhooks/jamhooks';

// While the app repo is private, a link into it would 404 for every reader, so links to
// unpublished files (the source, docs/internals/, ...) keep only their text. Turn this on
// when the app repo goes public: those links then point at the file at the synced tag,
// and each reference page's "Edit page" link opens the file in the app repo.
const LINK_TO_SOURCE = false;

// The app files that become pages, in sidebar order: [path in the app repo, page slug].
const PAGES = [
  ['docs/FLOWS.md', 'flows'],
  ['docs/RUNTIME.md', 'runtime'],
  ['docs/CONFIGURATION.md', 'configuration'],
  ['docs/DEPLOYMENT.md', 'deployment'],
  ['docs/OPERATIONS.md', 'operations'],
  ['docs/HARDENING.md', 'hardening'],
  ['docs/PRIVACY.md', 'privacy'],
  ['docs/API.md', 'api'],
  ['CHANGELOG.md', 'changelog'],
];
const SLUG_BY_PATH = new Map(PAGES);
const RELEASE_TAG = /^v\d+\.\d+\.\d+$/;

function main() {
  const { values } = parseArgs({
    options: {
      repo: { type: 'string', default: '../jamhooks' },
      version: { type: 'string' },
      latest: { type: 'boolean', default: false },
    },
  });
  const repo = resolve(values.repo);
  const git = (...args) =>
    execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });

  let tag;
  if (values.latest) {
    tag = git('tag', '--list', 'v*', '--sort=-v:refname')
      .split('\n')
      .find((t) => RELEASE_TAG.test(t));
    if (!tag) fail(`no vX.Y.Z tag in ${repo}`);
  } else {
    tag = values.version ?? readFileSync(VERSION_FILE, 'utf8').trim();
  }
  if (!RELEASE_TAG.test(tag)) fail(`"${tag}" is not a release tag (vX.Y.Z)`);

  const pages = PAGES.map(([path, slug], i) => {
    let text;
    try {
      text = git('show', `${tag}:${path}`);
    } catch {
      fail(`${path} does not exist at ${tag} in ${repo}`);
    }
    return [slug, convert(text, path, i + 1, tag)];
  });

  rmSync(OUT_DIR, { recursive: true, force: true });
  mkdirSync(OUT_DIR, { recursive: true });
  for (const [slug, page] of pages) writeFileSync(resolve(OUT_DIR, `${slug}.md`), page);
  writeFileSync(VERSION_FILE, `${tag}\n`);
  console.log(`Synced ${pages.length} reference pages from jamhooks ${tag}.`);
}

function convert(text, path, order, tag) {
  const lines = text.replace(/\r\n/g, '\n').split('\n');
  const h1 = lines.findIndex((l) => l.startsWith('# '));
  if (h1 === -1) fail(`${path} at ${tag} has no "# " title line`);
  const title = lines[h1].slice(2).trim();
  lines.splice(h1, 1);
  const body = rewriteLinks(lines, path, tag).join('\n').trim();

  const editUrl = LINK_TO_SOURCE ? JSON.stringify(`${APP_REPO_URL}/edit/master/${path}`) : 'false';
  return [
    '---',
    `title: ${JSON.stringify(title)}`,
    `editUrl: ${editUrl}`,
    'sidebar:',
    `  order: ${order}`,
    '---',
    '',
    `<!-- Generated by scripts/sync-reference.mjs from ${path} at jamhooks ${tag}.`,
    `     Do not edit here: change ${path} in the app repo, then re-sync. -->`,
    '',
    body,
    '',
  ].join('\n');
}

// Rewrites inline links outside fenced code blocks. Images and same-page anchors are
// left alone; so is anything with a scheme (https:, mailto:, ...).
function rewriteLinks(lines, path, tag) {
  let fence = null;
  return lines.map((line) => {
    const marker = line.match(/^\s*(`{3,}|~{3,})/);
    if (marker) {
      if (fence === null) fence = marker[1][0];
      else if (marker[1][0] === fence) fence = null;
      return line;
    }
    if (fence !== null) return line;
    return line.replace(/(!?)\[([^\]]*)\]\(([^)\s]+)\)/g, (link, bang, label, target) => {
      if (bang || target.startsWith('#') || /^[a-z][a-z0-9+.-]*:/i.test(target)) return link;
      const [file, hash] = splitHash(target);
      const resolved = posix.normalize(posix.join(posix.dirname(path), file));
      const slug = SLUG_BY_PATH.get(resolved);
      if (slug) return `[${label}](/reference/${slug}/${hash})`;
      if (LINK_TO_SOURCE) {
        const kind = resolved.endsWith('/') ? 'tree' : 'blob';
        return `[${label}](${APP_REPO_URL}/${kind}/${tag}/${resolved}${hash})`;
      }
      return label;
    });
  });
}

function splitHash(target) {
  const i = target.indexOf('#');
  return i === -1 ? [target, ''] : [target.slice(0, i), target.slice(i)];
}

function fail(message) {
  console.error(`sync-reference: ${message}`);
  process.exit(1);
}

main();
